@pytest.fixture()
def web(tmp_path, monkeypatch):
    """A fake web as in test_web_page: {url: Response}; every other URL raises like an unreachable site."""
    monkeypatch.setattr(kb, "HOME", tmp_path)
    monkeypatch.setattr(site_icons, "public_host", lambda host: None)
    pages: dict[str, Response] = {}
    calls: list[str] = []

    def get(url, limit=web_page.PAGE_MAX_BYTES, accept=""):
        calls.append(url)
        if url not in pages:
            raise OSError("unreachable")
        return pages[url]
    return pages, calls, get


def atom():
    return Response(API, 200, {"content-type": "application/atom+xml"}, (FIXTURES / "arxiv-api-2607.25690.xml").read_bytes())


def abs_page():
    return Response(ABS, 200, {"content-type": "text/html; charset=utf-8", "x-frame-options": "SAMEORIGIN"},
                    (FIXTURES / "arxiv-abs-2607.25690.html").read_bytes())


def test_arxiv_links_are_recognised_in_every_form():
    assert web_page.arxiv_of("https://arxiv.org/abs/2607.25690") == ("2607.25690", "abs")
    assert web_page.arxiv_of("https://www.arxiv.org/abs/2607.25690v2") == ("2607.25690", "abs")
    assert web_page.arxiv_of("https://arxiv.org/pdf/2607.25690v1.pdf") == ("2607.25690", "pdf")
    assert web_page.arxiv_of("https://arxiv.org/html/2607.25690v2/") == ("2607.25690", "html")
    assert web_page.arxiv_of("http://arxiv.org/abs/cond-mat/0601001v3") == ("cond-mat/0601001", "abs")
    assert web_page.arxiv_of("https://arxiv.org/list/cond-mat/new") is None
    assert web_page.arxiv_of("https://example.org/abs/2607.25690") is None


def test_tex_accents_become_letters_and_math_is_left_for_the_client():
    assert web_page.tex_text("Johan F\\'elisaz") == "Johan Félisaz"
    assert web_page.tex_text('Schr\\"{o}dinger and {\\c c}a and \\v{S}tefan and G\\"odel') == "Schrödinger and ça and Štefan and Gödel"
    assert web_page.tex_text("Graphene/PtSe$_2$ at $\\'x$") == "Graphene/PtSe$_2$ at $\\'x$"
    assert web_page.tex_text("A long\n  title") == "A long title"


def test_an_abstract_page_answers_the_paper_from_the_api(web):
    pages, calls, get = web
    pages[API] = atom()
    pages[ABS] = abs_page()
    answer = web_page.page(ABS, get=get)
    assert answer["mode"] == "reader" and answer["source"] == "arxiv" and answer["math"] is True
    assert answer["title"] == "First-Principles Wannier Representation of Proximity Effects"
    assert answer["byline"] == AUTHORS
    assert answer["abstract"].startswith("Proximity effects in layered heterostructures are commonly represented by static")
    assert "Graphene/PtSe$_2$ develops" in answer["abstract"] and "\n" not in answer["abstract"]
    paper = answer["paper"]
    assert paper["arxiv"] == "2607.25690" and paper["version"] == "v2"
    assert paper["submitted"] == "28 Jul 2026" and paper["revised"] == "25 Oct 2026"
    assert paper["subjects"] == [
        {"code": "cond-mat.mes-hall", "name": "Mesoscale and Nanoscale Physics", "primary": True},
        {"code": "cond-mat.mtrl-sci", "name": "Materials Science", "primary": False},
        {"code": "physics.comp-ph", "name": "Computational Physics", "primary": False}]
    assert paper["doi"] == "10.48550/arXiv.2607.25690"
    assert paper["comment"] == "14 pages, 9 figures"
    assert answer["links"] == [{"label": "PDF", "url": "https://arxiv.org/pdf/2607.25690", "kind": "pdf"},
                               {"label": "Full text", "url": "https://arxiv.org/html/2607.25690v2", "kind": "reader"}]
    assert answer["html"] == ""
    # kept a day: asked again, nothing is fetched
    calls.clear()
    assert web_page.page(ABS, get=get)["byline"] == AUTHORS
    assert calls == []


def test_without_the_api_the_abstract_page_meta_tags_answer(web):
    pages, _, get = web
    pages[ABS] = abs_page()
    answer = web_page.page("https://arxiv.org/abs/2607.25690v2", prefer="reader", get=get)
    assert answer["source"] == "arxiv"
    assert answer["title"] == "First-Principles Wannier Representation of Proximity Effects"
    assert answer["byline"] == AUTHORS  # citation_author is "Last, First"
    assert "graphene/WSe$_2$" in answer["abstract"]
    assert answer["paper"]["submitted"] == "28 Jul 2026" and answer["paper"]["version"] == "v2"
    assert answer["paper"]["subjects"][0] == {"code": "cond-mat.mes-hall", "name": "Mesoscale and Nanoscale Physics", "primary": True}
    assert [link["label"] for link in answer["links"]] == ["PDF", "Full text"]


def test_no_html_version_means_no_full_text_link(web):
    pages, _, get = web
    pages[API] = atom()
    page = abs_page()
    page.body = page.body.replace(b"/html/2607.25690v2", b"/nothing/here")
    pages[ABS] = page
    answer = web_page.page(ABS, get=get)
    assert [link["label"] for link in answer["links"]] == ["PDF"]


def test_a_pdf_link_stays_a_pdf_unless_the_reader_is_asked_for(web):
    pages, _, get = web
    pdf = "https://arxiv.org/pdf/2607.25690"
    pages[pdf] = Response(pdf, 200, {"content-type": "application/pdf"}, b"%PDF-1.7 ...")
    pages[API] = atom()
    pages[ABS] = abs_page()
    assert web_page.page(pdf, get=get)["mode"] == "pdf"
    assert web_page.page(pdf, prefer="reader", get=get)["source"] == "arxiv"


def test_the_html_full_text_is_read_with_the_paper_around_it(web):
    pages, _, get = web
    full = "https://arxiv.org/html/2607.25690v2"
    pages[API] = atom()
    pages[ABS] = abs_page()
    pages[full] = Response(full, 200, {"content-type": "text/html; charset=utf-8"}, LATEXML.encode())
    answer = web_page.page(full, get=get)
    assert answer["mode"] == "reader" and answer["source"] == "arxiv" and answer["math"] is True
    assert answer["byline"] == AUTHORS and answer["paper"]["version"] == "v2"
    assert answer.get("abstract") is None  # the full text carries its own
    body = answer["html"]
    assert "Introduction" in body and "Band structure of graphene/hBN/Co(0001)." in body
    assert "$\\Delta(\\omega)=V^{\\dagger}G(\\omega)V$" in body
    assert body.count("\\Delta(\\omega)") == 1  # the annotation is not repeated after the formula
    assert "First-Principles Wannier" not in body  # the header shows the title
    assert "October 25, 2026" not in body, "the header has the dates"
    assert "University of Somewhere" not in body and "LaTeXML" not in body and "Contents" not in body
    assert [link["label"] for link in answer["links"]] == ["PDF", "Abstract"]


def test_an_unknown_arxiv_id_falls_back_to_the_page(web):
    pages, _, get = web
    answer = web_page.page("https://arxiv.org/abs/2607.99999", get=get)
    assert answer["mode"] == "blocked"


def test_old_style_ids_ask_the_api_by_their_full_id(web):
    pages, calls, get = web
    web_page.page("https://arxiv.org/abs/cond-mat/0601001v1", get=get)
    assert "http://export.arxiv.org/api/query?id_list=cond-mat/0601001" in calls


def test_an_arxiv_doi_opens_the_arxiv_paper(web):
    pages, calls, get = web
    pages[API] = atom()
    pages[ABS] = abs_page()
    answer = web_page.page("https://doi.org/10.48550/arXiv.2607.25690", get=get)
    assert answer["source"] == "arxiv" and answer["byline"] == AUTHORS
    assert not any("openalex" in c for c in calls)
