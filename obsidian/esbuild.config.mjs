import esbuild from "esbuild";
import builtins from "builtin-modules";
import { readFileSync, writeFileSync } from "fs";
import { dataUrl, homeCss } from "../zotero-plugin/ui-src/home-assets.mjs";

// `import HOME_CSS from "sb-home-css"` (src/home.ts): Home's sheet with every font and cover photo as a data: URL,
// since Obsidian serves a plugin's main.js and styles.css only.
const homeCssModule = {
  name: "sb-home-css",
  setup(build) {
    build.onResolve({ filter: /^sb-home-css$/ }, () => ({ path: "sb-home-css", namespace: "sb-home-css" }));
    build.onLoad({ filter: /.*/, namespace: "sb-home-css" }, () => ({ contents: homeCss(dataUrl), loader: "text" }));
  },
};

await esbuild.build({
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: ["obsidian", "electron", "@codemirror/*", "@lezer/*", ...builtins],
  format: "cjs",
  target: "es2020",
  outfile: "main.js",
  plugins: [homeCssModule],
  logLevel: "info",
});

// styles.css (spec 005 C3): the shared chat's own component CSS (sb-ai-*, sb-fp-*, sb-rp-*) is injected at
// runtime by ChatView.style()/FindView.style()/ReportView.style() (ui-src/src/chat/*.js), the same as in
// Zotero's chrome documents, so it needs no build step here. What DOES need building statically is (1) the
// --sb-ui-* token mapping (tokens-obsidian.css: nothing injects this, and it must be present before the chat's
// own CSS reads it) and (2) ui-src's own trivial component sheet (ui.css, so a stray sb-p-* stays styled if
// ever used) and (3) this plugin's remaining panels (search/related/duplicates/status/zotero, styles-panels.css
// -- everything that isn't the old sbc-* chat CSS, which is gone: the chat is ui-src's ChatView now).
const uiCss = readFileSync("../zotero-plugin/ui-src/styles/ui.css", "utf8");
const tokensCss = readFileSync("../zotero-plugin/ui-src/styles/tokens-obsidian.css", "utf8");
const panelsCss = readFileSync("styles-panels.css", "utf8");
writeFileSync("styles.css", [
  "/* Generated by esbuild.config.mjs from ui-src's tokens/ui.css and this plugin's styles-panels.css. Edit those, not this file. */",
  tokensCss, uiCss, panelsCss,
].join("\n\n"));
console.log("built styles.css");
